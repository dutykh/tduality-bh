# Tiny Re/Im roundoff noise below this threshold is printed as 0
# in readable files. Full-precision files are unchanged.
const DISPLAY_ZERO_TOL = bf("1e-20")

# Tiny real parts below this value are chopped to zero in plots only.
const PLOT_ZERO_TOL = bf("1e-12")

# Stable-mode matching tolerance between the three N runs.
const STABLE_RELTOL = bf("1e-4")
const STABLE_ABSTOL = bf("1e-4")

# The generalized eigenproblem usually contains a static Omega = 0
# solution. This is not a QNM and is discarded by default.
const DISCARD_ZERO_MODE = true
const ZERO_MODE_TOL = bf("1e-30")

# With time dependence exp(-i omega t), QNMs have Im(Omega) < 0.
const KEEP_ONLY_DAMPED = true
const DAMPING_TOL = bf("1e-18")

# Keep only one representative branch of the +/- Re(Omega) symmetry.
# This is useful for tables. Set this to false if the full symmetric
# spectrum is desired.
const KEEP_REPRESENTATIVE_BRANCH = false
const REPRESENTATIVE_RE_TOL = bf("1e-10")

# Threshold used only to split stable modes into oscillatory and
# purely imaginary lists.
const PURE_IMAG_RE_TOL = bf("1e-10")

# These must match the Maple files.
const N_VALS = (190, 195, 200)

# Plot settings.

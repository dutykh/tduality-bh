const SAVE_HTML_PLOTS = true

# This code solves:
#
#     (M0 + i*Omega*M1 + Omega^2*M2)b = 0.
#

matfile(prefix::AbstractString, n::Integer) =
    joinpath(DATA_DIR, "$(prefix)-$(n)-$(FILETAG).mat")


# ============================================================
# T-Duality black-hole spectral QNM solver
#
# Maple exports matrices for the quadratic pencil
#
#     M0 + i*Omega*M1 + Omega^2*M2 = 0.
#
# This Julia code solves the corresponding generalized
# eigenvalue problem and identifies modes stable under the
# three spectral resolutions generated by the Maple assembler.
#
# This version matches the attached Maple assembler:
#
#     filetag := cat("s", s, "_L", L, "_q", q)
#
# Hence the files are, for example,
#
#     M0-90-s0_L0_q0.mat
#     M1-90-s0_L0_q0.mat
#     M2-90-s0_L0_q0.mat
#
# 
# This version also checks the unfiltered finite spectra for
# roots with Im(Omega) > 0. With the convention exp(-i omega t),
# such roots would correspond to growing modes. The code writes
# per-resolution positive-Im candidate files and a final stable
# positive-Im report. If no stable positive-Im mode is found,
# the report explicitly says: "No unstable mode detected."
# ============================================================

# ------------------------------------------------------------
# Field sector, angular momentum, and q deformation tag.
#
# These must match the Maple assembler:
#
# s = 0 : massless scalar,       L >= 0
# s = 1 : electromagnetic field, L >= 1
#
#
# The Maple file tag is:
#
#     s<S>_L<L>_q<A>
#
# The quantity DEFORMATION_TAG is a string because it must match
# exactly the way Maple wrote the value of q into the file name.
# Examples: "0", "0.1", "0.5", "1", "629".
# ------------------------------------------------------------

const SPIN = 0
const ELL  = 0
const DEFORMATION_TAG = "0"

function validate_sector(s::Integer, ell::Integer)
    if s == 0
        ell >= 0 || error("For s=0 one needs ell >= 0.")
    elseif s == 1
        ell >= 1 || error("For s=1 one needs ell >= 1.")
    elseif s == 2
        ell >= 2 || error("For s=2 one needs ell >= 2.")
    else
        error("Unknown spin sector s=$s. Use s=0, 1, or 2.")
    end
    return nothing
end

validate_sector(SPIN, ELL)

const EPSILON = 1 - SPIN^2
const FILETAG = "s$(SPIN)_L$(ELL)_q$(DEFORMATION_TAG)"

function sector_name(s::Integer)
    if s == 0
        return "scalar"
    elseif s == 1
        return "electromagnetic"
    elseif s == 2
        return "gravitational"
    else
        return "unknown"
    end
end

